-- Source tables follow TV2's source-row grain; derived lookup is not an official codebook.
CREATE TABLE IF NOT EXISTS raw_meta.source_file (
 file_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 family text NOT NULL CHECK (family IN ('employment','accessions','separations')),
 report_month text NOT NULL CHECK (report_month ~ '^[0-9]{4}(0[1-9]|1[0-2])$'),
 version text NOT NULL, filename text NOT NULL UNIQUE, sha256 text NOT NULL UNIQUE,
 schema_hash text NOT NULL, size_bytes bigint NOT NULL, row_count bigint NOT NULL,
 column_count integer NOT NULL, source_url text NOT NULL,
 is_active boolean NOT NULL DEFAULT true,
 status text NOT NULL DEFAULT 'REGISTERED' CHECK (status IN ('REGISTERED','LOADED')),
 registered_at timestamptz NOT NULL DEFAULT now(),
 loaded_at timestamptz,
 UNIQUE (family, report_month)
);
CREATE TABLE IF NOT EXISTS audit.load_run (
 run_id uuid PRIMARY KEY, file_id bigint REFERENCES raw_meta.source_file,
 job text NOT NULL, family text, report_month text, version text, filename text,
 sha256 text, expected_rows bigint, actual_rows bigint,
 status text NOT NULL CHECK (status IN ('RUNNING','SUCCESS','SKIPPED','FAIL')),
 started_at timestamptz NOT NULL, finished_at timestamptz,
 duration_seconds numeric, error text, code_version text NOT NULL
);
CREATE TABLE IF NOT EXISTS audit.dq_issue (
 issue_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 run_id uuid NOT NULL REFERENCES audit.load_run,
 file_id bigint NOT NULL REFERENCES raw_meta.source_file,
 source_row_ordinal bigint, column_name text NOT NULL, rule_id text NOT NULL,
 details text NOT NULL, affected_rows bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS dq_issue_file ON audit.dq_issue(file_id);
CREATE TABLE IF NOT EXISTS ref.derived_lookup (
 relation text, report_month text, code text, label text, observed_rows text,
 provenance text, load_status text, exception text, observed_labels text,
 fedscope_label_check text, ehri_label text, ehri_label_check text
);
CREATE UNIQUE INDEX IF NOT EXISTS derived_ready_key
 ON ref.derived_lookup(relation, report_month, code) WHERE load_status = 'READY';

