COMMENT ON TABLE dw.fact_accessions IS
    'PROPOSED pending TV4. Grain one Accessions source row; separate report and effective month roles.';
COMMENT ON TABLE dw.fact_separations IS
    'PROPOSED pending TV4. Grain one Separations source row; separate report and effective month roles.';
COMMENT ON TABLE dw.dim_agency IS
    'Derived lookup by report month; uniqueness gated before lookup. PARTIAL official reference validation, pending TV4 approval.';
