-- G2 implementation proposal based on TV2 source mapping.
-- Grain, dimensions and hierarchy await TV4 approval; source lookup remains PARTIAL.
CREATE TABLE IF NOT EXISTS dw.dim_month (
    month_key integer PRIMARY KEY,
    yyyymm text UNIQUE,
    calendar_year integer,
    calendar_month integer,
    CHECK (month_key = 0 OR (
        yyyymm ~ '^[0-9]{4}(0[1-9]|1[0-2])$'
        AND month_key = yyyymm::integer
        AND calendar_year = month_key / 100
        AND calendar_month = month_key % 100
    ))
);
INSERT INTO dw.dim_month (month_key) VALUES (0) ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS dw.dim_agency (
    agency_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month_key integer NOT NULL REFERENCES dw.dim_month(month_key),
    agency_code text NOT NULL,
    agency_label text NOT NULL,
    provenance text NOT NULL,
    verification_status text NOT NULL,
    UNIQUE (month_key, agency_code)
);
INSERT INTO dw.dim_agency
    (agency_key, month_key, agency_code, agency_label, provenance, verification_status)
VALUES (0, 0, 'UNKNOWN', 'Unknown', 'TECHNICAL_UNKNOWN', 'PARTIAL')
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS dw.dim_action_category (
    category_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    month_key integer NOT NULL REFERENCES dw.dim_month(month_key),
    family text NOT NULL CHECK (family IN ('accessions', 'separations', 'unknown')),
    category_code text NOT NULL,
    category_label text NOT NULL,
    provenance text NOT NULL,
    verification_status text NOT NULL,
    UNIQUE (month_key, family, category_code)
);
INSERT INTO dw.dim_action_category
    (category_key, month_key, family, category_code, category_label, provenance, verification_status)
VALUES (0, 0, 'unknown', 'UNKNOWN', 'Unknown', 'TECHNICAL_UNKNOWN', 'PARTIAL')
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS dw.fact_employment_snapshot (
    file_id bigint NOT NULL,
    source_row_ordinal bigint NOT NULL,
    report_month_key integer NOT NULL REFERENCES dw.dim_month(month_key),
    snapshot_month_key integer NOT NULL REFERENCES dw.dim_month(month_key),
    agency_key bigint NOT NULL REFERENCES dw.dim_agency(agency_key),
    agency_code text,
    agency_lookup_state text NOT NULL,
    count_value bigint NOT NULL CHECK (count_value >= 0),
    dq_flags text[] NOT NULL,
    PRIMARY KEY (file_id, source_row_ordinal),
    FOREIGN KEY (file_id, source_row_ordinal)
        REFERENCES ods.ods_employment_record(file_id, source_row_ordinal)
);

CREATE TABLE IF NOT EXISTS dw.fact_accessions (
    file_id bigint NOT NULL,
    source_row_ordinal bigint NOT NULL,
    report_month_key integer NOT NULL REFERENCES dw.dim_month(month_key),
    effective_month_key integer NOT NULL REFERENCES dw.dim_month(month_key),
    agency_key bigint NOT NULL REFERENCES dw.dim_agency(agency_key),
    category_key bigint NOT NULL REFERENCES dw.dim_action_category(category_key),
    agency_code text,
    agency_lookup_state text NOT NULL,
    category_code text,
    category_lookup_state text NOT NULL,
    count_value bigint NOT NULL CHECK (count_value >= 0),
    dq_flags text[] NOT NULL,
    PRIMARY KEY (file_id, source_row_ordinal),
    FOREIGN KEY (file_id, source_row_ordinal)
        REFERENCES ods.ods_accessions_record(file_id, source_row_ordinal)
);

CREATE TABLE IF NOT EXISTS dw.fact_separations (
    file_id bigint NOT NULL,
    source_row_ordinal bigint NOT NULL,
    report_month_key integer NOT NULL REFERENCES dw.dim_month(month_key),
    effective_month_key integer NOT NULL REFERENCES dw.dim_month(month_key),
    agency_key bigint NOT NULL REFERENCES dw.dim_agency(agency_key),
    category_key bigint NOT NULL REFERENCES dw.dim_action_category(category_key),
    agency_code text,
    agency_lookup_state text NOT NULL,
    category_code text,
    category_lookup_state text NOT NULL,
    count_value bigint NOT NULL CHECK (count_value >= 0),
    dq_flags text[] NOT NULL,
    PRIMARY KEY (file_id, source_row_ordinal),
    FOREIGN KEY (file_id, source_row_ordinal)
        REFERENCES ods.ods_separations_record(file_id, source_row_ordinal)
);

CREATE INDEX IF NOT EXISTS fact_employment_snapshot_month_agency
    ON dw.fact_employment_snapshot(snapshot_month_key, agency_key);
CREATE INDEX IF NOT EXISTS fact_accessions_report_agency
    ON dw.fact_accessions(report_month_key, agency_key);
CREATE INDEX IF NOT EXISTS fact_separations_report_agency
    ON dw.fact_separations(report_month_key, agency_key);

